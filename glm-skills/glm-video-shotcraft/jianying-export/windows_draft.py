"""Windows JianYing/CapCut draft installation module.

Implemented per pyJianYingDraft supported paths (verified upstream on JianYing 5.9 and 10.8).
Run a minimal smoke test before first production export (references/jianying-export.md).

Key characteristics on Windows:
- Entry file is draft_content.json (pyJianYingDraft native output);
- No root_meta_info.json registry needed; app auto-scans draft directories;
- bundle_media is enabled by default to keep drafts portable and prevent missing media errors.
"""

import json
import os
import shutil
import subprocess
import time
import unicodedata


def default_draft_root() -> str:
    """Default Windows draft root directory; override if customized in app settings."""
    for candidate in (
        os.path.expandvars(
            r"%LOCALAPPDATA%\JianyingPro\User Data\Projects\com.lveditor.draft"),
        os.path.expanduser(r"~\JianyingPro Drafts"),
    ):
        if os.path.isdir(candidate):
            return candidate
    raise FileNotFoundError(
        "JianYing draft root directory not found; pass explicitly from app settings")


def jianying_running() -> bool:
    out = subprocess.run(
        ["tasklist", "/FI", "IMAGENAME eq JianyingPro.exe", "/NH"],
        capture_output=True, text=True).stdout
    return "JianyingPro" in out


def _validate_draft_name(draft_name: str, root: str) -> str:
    """Validate draft name and return target path, rejecting path traversal."""
    if (not draft_name or draft_name in (".", "..")
            or "/" in draft_name or "\\" in draft_name or ":" in draft_name
            or os.path.isabs(draft_name)):
        raise ValueError(
            f"Invalid draft name {draft_name!r}: cannot be empty, absolute, or contain path separators")
    target = os.path.realpath(os.path.join(root, draft_name))
    if os.path.dirname(target) != os.path.realpath(root):
        raise ValueError(f"Draft name {draft_name!r} escapes root directory: {target}")
    return os.path.join(root, draft_name)


def _write_json_atomic(path: str, obj: dict) -> None:
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False)
    os.replace(tmp, path)


def _trash_dir(root: str) -> str:
    """Trash directory for deleted drafts to prevent ghost draft recognition."""
    d = os.path.join(root, ".vs-export-trash")
    os.makedirs(d, exist_ok=True)
    return d


def _name_key(name: str) -> str:
    """Normalized casefolded key for case-insensitive file matching."""
    return unicodedata.normalize("NFC", name).casefold()


def _unique_name(name: str, used_keys: set) -> str:
    """Generate unique filename with incremental suffix."""
    if _name_key(name) not in used_keys:
        return name
    stem, ext = os.path.splitext(name)
    i = 2
    while _name_key(f"{stem}-{i}{ext}") in used_keys:
        i += 1
    return f"{stem}-{i}{ext}"


def bundle_media(draft_dir: str, draft_name: str, draft_root: str) -> None:
    """Copy all media assets into Resources/ and rewrite material paths."""
    content_path = os.path.join(draft_dir, "draft_content.json")
    with open(content_path, encoding="utf-8") as f:
        content = json.load(f)

    res_dir = os.path.join(draft_dir, "Resources")
    os.makedirs(res_dir, exist_ok=True)
    final_base = os.path.join(draft_root, draft_name, "Resources")
    mapping: dict[str, str] = {}
    used_keys: set[str] = set()
    for kind in ("videos", "audios"):
        for m in content["materials"].get(kind, []):
            src = m["path"]
            if src.startswith(final_base + os.sep):
                # Retry scenario: path already at final destination
                local = os.path.join(res_dir, os.path.basename(src))
                if not os.path.exists(local):
                    raise FileNotFoundError(
                        f"Material points to final path but staging copy is missing: {src}")
                used_keys.add(_name_key(os.path.basename(src)))
                continue
            if src not in mapping:
                name = _unique_name(os.path.basename(src), used_keys)
                used_keys.add(_name_key(name))
                shutil.copy2(src, os.path.join(res_dir, name))
                mapping[src] = os.path.join(final_base, name)
            m["path"] = mapping[src]

    _write_json_atomic(content_path, content)


def install(draft_dir: str, draft_name: str, draft_root: str | None = None,
            bundle: bool = True) -> str:
    """Install draft directory generated by pyJianYingDraft into Windows draft library."""
    if jianying_running():
        raise RuntimeError("JianYing is running; please exit completely before installing")
    root = draft_root or default_draft_root()
    target = _validate_draft_name(draft_name, root)
    if bundle:
        bundle_media(draft_dir, draft_name, root)
    old = None
    if os.path.exists(target):
        old = os.path.join(
            _trash_dir(root),
            f"{draft_name}.replaced-{time.strftime('%Y%m%d-%H%M%S')}")
        os.rename(target, old)
    try:
        shutil.move(draft_dir, target)
    except BaseException:
        try:  # Rollback: reset old draft
            if os.path.exists(target):
                if os.path.exists(draft_dir):
                    shutil.rmtree(target, ignore_errors=True)
                else:
                    shutil.move(target, draft_dir)
            if old and os.path.exists(old):
                os.rename(old, target)
        finally:
            raise
    if old:
        try:
            shutil.rmtree(old)
        except OSError as e:
            print(f"[warn] Failed to clean up old draft backup: {old} ({e})")
    return target


def uninstall(draft_name: str, draft_root: str | None = None) -> None:
    """Delete draft by moving to trash directory first."""
    if jianying_running():
        raise RuntimeError("JianYing is running; please exit completely before installing")
    root = draft_root or default_draft_root()
    target = _validate_draft_name(draft_name, root)
    if not os.path.exists(target):
        return
    tmp = os.path.join(
        _trash_dir(root),
        f"{draft_name}.uninstall-{time.strftime('%Y%m%d-%H%M%S')}")
    os.rename(target, tmp)
    try:
        shutil.rmtree(tmp)
    except OSError as e:
        print(f"[warn] Remnants in trash directory, please clean manually: {tmp} ({e})")
