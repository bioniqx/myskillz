def _backup_registry() -> str:
    bak = ROOT_META + time.strftime(".%Y%m%d-%H%M%S.bak")
    shutil.copy2(ROOT_META, bak)
    return bak


def _trash_dir() -> str:
    """Trash directory for deleted drafts to prevent ghost draft recognition."""
    d = os.path.join(DRAFT_ROOT, ".vs-export-trash")
    os.makedirs(d, exist_ok=True)
    return d


def install(draft_dir: str, draft_name: str, info: dict) -> str:
    """Install macified draft into draft library and update registry."""
    if jianying_running():
        raise RuntimeError("JianYing is running; please quit completely (Cmd+Q) before running")
    target = _validate_draft_name(draft_name)

    # 1) Parse registry before modifying disk
    with open(ROOT_META, encoding="utf-8") as f:
        root = json.load(f)
    # 2) Backup registry
    bak = _backup_registry()
    # 3) Move existing draft to trash backup before overwrite
    old = None
    if os.path.exists(target):
        old = os.path.join(
            _trash_dir(),
            f"{draft_name}.replaced-{time.strftime('%Y%m%d-%H%M%S')}")
        os.rename(target, old)
    try:
        shutil.move(draft_dir, target)
        root["all_draft_store"] = [e for e in root["all_draft_store"]
                                   if e.get("draft_name") != draft_name]
        root["all_draft_store"].insert(0, _registry_entry(info, draft_name))
        _write_json_atomic(ROOT_META, root)
    except BaseException:
        try:  # Rollback on failure
            if os.path.exists(target):
                if os.path.exists(draft_dir):
                    shutil.rmtree(target, ignore_errors=True)
                else:
                    shutil.move(target, draft_dir)
            if old and os.path.exists(old):
                os.rename(old, target)
            shutil.copy2(bak, ROOT_META)
        finally:
            raise
    if old:
        try:
            shutil.rmtree(old)
        except OSError as e:
            print(f"[warn] Failed to clean up old draft backup: {old} ({e})")
    return bak


def uninstall(draft_name: str) -> None:
    """Delete specified draft and remove from registry."""
    if jianying_running():
        raise RuntimeError("JianYing is running; please quit completely (Cmd+Q) before running")
    target = _validate_draft_name(draft_name)
    with open(ROOT_META, encoding="utf-8") as f:
        root = json.load(f)
    _backup_registry()
    tmp = None
    if os.path.exists(target):
        tmp = os.path.join(
            _trash_dir(),
            f"{draft_name}.uninstall-{time.strftime('%Y%m%d-%H%M%S')}")
        os.rename(target, tmp)
    try:
        root["all_draft_store"] = [e for e in root["all_draft_store"]
                                   if e.get("draft_name") != draft_name]
        _write_json_atomic(ROOT_META, root)
    except BaseException:
        if tmp and os.path.exists(tmp):
            os.rename(tmp, target)
        raise
    if tmp:
        try:
            shutil.rmtree(tmp)
        except OSError as e:
            print(f"[warn] Registry updated, backup remains in trash directory: {tmp} ({e})")
