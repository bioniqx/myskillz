// Motion common utilities — Shared across 48 cards from motion-lab incubation:
// Easing table E / segmented progress seg / lerp / deterministic pseudorandom rand + DesignStage coordinate container.
// All pure functions driven by useCurrentFrame, satisfying Remotion deterministic rendering requirements.
import React from 'react';
import { AbsoluteFill, useCurrentFrame, useVideoConfig } from 'remotion';

export const E = {
  linear: (t: number) => t,
  inQuad: (t: number) => t * t,
  outQuad: (t: number) => t * (2 - t),
  inOutQuad: (t: number) => (t < 0.5 ? 2 * t * t : -1 + (4 - 2 * t) * t),
  inCubic: (t: number) => t * t * t,
  outCubic: (t: number) => 1 - Math.pow(1 - t, 3),
  inOutCubic: (t: number) => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2),
  outQuart: (t: number) => 1 - Math.pow(1 - t, 4),
  outQuint: (t: number) => 1 - Math.pow(1 - t, 5),
  inQuart: (t: number) => t * t * t * t,
  outExpo: (t: number) => (t === 1 ? 1 : 1 - Math.pow(2, -10 * t)),
  inExpo: (t: number) => (t === 0 ? 0 : Math.pow(2, 10 * t - 10)),
  outBack: (t: number, s = 1.70158) => 1 + (s + 1) * Math.pow(t - 1, 3) + s * Math.pow(t - 1, 2),
  inBack: (t: number, s = 1.70158) => (s + 1) * t * t * t - s * t * t,
  outElastic: (t: number) =>
    t === 0 ? 0 : t === 1 ? 1 : Math.pow(2, -10 * t) * Math.sin((t * 10 - 0.75) * ((2 * Math.PI) / 3)) + 1,
  spring: (t: number, bounce = 0.25) => {
    const w = 8 + 8 * (1 - bounce);
    return 1 - Math.exp(-6 * t) * Math.cos(w * t * bounce * 2.2);
  },
};

export const lerp = (t: number, a: number, b: number) => a + (b - a) * t;

// Segmented progress: normalizes t within [t0, t1] then applies ease, clamped out of bounds — timeline primitive for all motion
export const seg = (t: number, t0: number, t1: number, ease: (x: number) => number = E.linear) =>
  ease(Math.min(1, Math.max(0, (t - t0) / (t1 - t0))));

// Deterministic pseudorandom (equivalent to Remotion random(seed); reproducible across frames/renders with same seed)
export const rand = (seed: number) => {
  const x = Math.sin(seed * 127.1 + 311.7) * 43758.5453;
  return x - Math.floor(x);
};

// Composition-normalized progress t in [0, 1]: final frame is exactly 1 (matches frame-by-frame t mapping in sample renders)
export const useT = () => {
  const frame = useCurrentFrame();
  const { durationInFrames } = useVideoConfig();
  return Math.min(1, frame / Math.max(1, durationInFrames - 1));
};

// Design coordinate container: content drawn at w x h (default 480x270), scaled proportionally to fill composition.
// Parameters for motion-lab animations are calibrated in this space; values remain constant regardless of output scale.
// raster='zoom': scales via CSS zoom (layout-time scaling; glyphs rasterized at target resolution, equivalent to original DPR=4 capture pipeline).
// Default is transform scale (composite-time scaling). In text-dense small font scenarios,
// the two pipelines have perceptible glyph rendering differences; use zoom to match reference captures.
export const DesignStage: React.FC<{
  w?: number;
  h?: number;
  bg?: string;
  raster?: 'scale' | 'zoom';
  children: React.ReactNode;
}> = ({ w = 480, h = 270, bg, raster = 'scale', children }) => {
  const { width } = useVideoConfig();
  const scale = width / w;
  return (
    <AbsoluteFill style={{ background: bg ?? '#000', overflow: 'hidden' }}>
      <div
        style={{
          position: 'absolute',
          left: 0,
          top: 0,
          width: w,
          height: h,
          overflow: 'hidden',
          ...(raster === 'zoom'
            ? { zoom: scale }
            : { transform: `scale(${scale})`, transformOrigin: 'top left' }),
        }}
      >
        {children}
      </div>
    </AbsoluteFill>
  );
};
