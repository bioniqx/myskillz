import type React from "react";

/** Inspector control descriptor — declares tunable properties of a card */
export type PropField =
  | { type: "text"; key: string; label: string; default: string }
  | { type: "textarea"; key: string; label: string; default: string }
  | {
      type: "number";
      key: string;
      label: string;
      default: number;
      min?: number;
      max?: number;
      step?: number;
      /** Display unit, e.g. "s" / "px" */
      unit?: string;
    }
  | {
      type: "slider";
      key: string;
      label: string;
      default: number;
      min: number;
      max: number;
      step: number;
      unit?: string;
    }
  | { type: "color"; key: string; label: string; default: string }
  | {
      type: "select";
      key: string;
      label: string;
      default: string;
      options: { value: string; label: string }[];
    }
  | { type: "boolean"; key: string; label: string; default: boolean };

export interface CardDef {
  themeKey?: string;
  id: string;
  /** Name: card or manifest title */
  name: string;
  /** English name: generated by gen-index from gallery data */
  nameEn?: string;
  category: string;
  /** "audio"/"video": media cards — bypass TimeRemap for native playback; */
  /** trim/speed passed via props as trimBefore/playbackRate */
  /** video retains layer styling, audio has no visual component */
  kind?: "visual" | "audio" | "video";
  /** Original card duration (frames, at sourceFps) — default duration for new clips */
  durationInFrames: number;
  /** Card frame rate for duration and timing (default CARD_FPS); */
  /** film units use manifest fps */
  sourceFps?: number;
  /** Timing semantics (default "frames"):
   *  - "frames": frame-by-frame animation at sourceFps;
   *  - "realtime": media driven by wall-clock time;
   *    scales duration without altering playback rate */
  timing?: "frames" | "realtime";
  /** Card design canvas (default 1920x1080) */
  width?: number;
  height?: number;
  component: React.ComponentType<Record<string, unknown>>;
  schema: PropField[];
  /** Asset library color badge */
  accent?: string;
  /** Injects source duration (frames) into this prop for dynamic fade-out calculations;
   *  fade-out follows clip duration instead of freezing */
  durationProp?: string;
  /** Asset library preview video path */
  preview?: string;
  /** Summary description (asset library tooltip) */
  summary?: string;
  /** English summary (from gallery translations stylesEn / cardsEn) */
  summaryEn?: string;
}

/** Card library standardized at 30fps: scales duration and speed if project fps differs */
export const CARD_FPS = 30;

/** Card authoring frame rate (default CARD_FPS) */
export const cardFps = (card: CardDef) => card.sourceFps ?? CARD_FPS;

/** Source duration in project fps */
export const sourceLength = (card: CardDef, projectFps: number) =>
  card.timing === "realtime"
    ? Math.max(2, Math.round((card.durationInFrames * projectFps) / cardFps(card)))
    : card.durationInFrames;

/** Frame rate used to measure clip.inOffset */
export const inOffsetFps = (card: CardDef | undefined, projectFps: number) =>
  !card || card.timing === "realtime" ? projectFps : cardFps(card);

/** Default duration and speed for new clips */
export const clipDefaultsFor = (card: CardDef, projectFps: number, sourceFrames = card.durationInFrames) => {
  const scale = projectFps / cardFps(card);
  const realtime = card.timing === "realtime";
  return {
    duration: Math.max(2, Math.round(sourceFrames * scale)),
    speed: realtime || scale === 1 ? 1 : 1 / scale,
  };
};

export const defaultsOf = (card: CardDef): Record<string, unknown> =>
  Object.fromEntries(card.schema.map((f) => [f.key, f.default]));

export const cardSize = (card: CardDef) => ({
  width: card.width ?? 1920,
  height: card.height ?? 1080,
});
